class I18nEngine {
  constructor() {
    this.storageKey = 'delta_neurons_selected_lang';
    this.currentLang = this.getSavedLanguage();
    this.dictionaries = I18N_DICTIONARIES;
  }

  getSavedLanguage() {
    try {
      const saved = localStorage.getItem(this.storageKey);
      if (saved && I18N_DICTIONARIES[saved]) return saved;
    } catch (e) {}
    return 'as'; // Default to Assamese as regional heritage
  }

  t(key) {
    const dict = this.dictionaries[this.currentLang] || this.dictionaries['en'];
    return dict[key] || (this.dictionaries['en'] ? this.dictionaries['en'][key] : key) || key;
  }

  setLanguage(langCode) {
    if (!this.dictionaries[langCode]) {
      console.warn(`Language ${langCode} not available. Defaulting to English.`);
      langCode = 'en';
    }
    this.currentLang = langCode;
    try {
      localStorage.setItem(this.storageKey, langCode);
    } catch (e) {}

    // Sync speech engine if available
    if (window.VoiceNER && typeof window.VoiceNER.setLanguage === 'function') {
      window.VoiceNER.setLanguage(langCode);
    }

    this.applyTranslations();

    // Trigger custom event so reactive components can re-render in chosen language
    window.dispatchEvent(new CustomEvent('deltaNeuronsLanguageChanged', { detail: { lang: langCode } }));
  }

  applyTranslations() {
    const lang = this.currentLang;
    const dict = this.dictionaries[lang] || this.dictionaries['en'];

    // Update <html lang="...">
    document.documentElement.lang = lang;

    // Update all elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Update placeholders
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    // Update titles / tooltips
    const titles = document.querySelectorAll('[data-i18n-title]');
    titles.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.title = dict[key];
      }
    });

    // Update select dropdowns value if present on page
    const selects = document.querySelectorAll('.lang-select, #language-select');
    selects.forEach(sel => {
      if (sel && sel.value !== lang) {
        sel.value = lang;
      }
    });
  }
}

// Export singleton
window.I18nEngine = new I18nEngine();
